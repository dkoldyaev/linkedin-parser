#!/usr/bin/env node
// Builds a loadable extension into extension/dist/.
//
//   node extension/build/build.mjs                    # development (load unpacked from extension/dist)
//   node extension/build/build.mjs --mode production  # production + zip for the Chrome Web Store

import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import { spawnSync } from 'node:child_process'
import { parseArgs } from 'node:util'
import { DIST_DIR, EXTENSION_DIR, resolveConfig } from './config.mjs'
import { buildManifest } from './manifest.mjs'

const { values: args } = parseArgs({
  options: {
    mode: { type: 'string', default: 'development' },
    zip: { type: 'boolean', default: false },
  },
})

const config = resolveConfig(args.mode)
const shouldZip = args.zip || config.mode === 'production'
const POPUP_SRC = path.join(EXTENSION_DIR, 'popup-src')

// Chrome extension ID = first 128 bits of sha256, hex digits 0-f mapped to a-p.
function extensionIdFrom(bytes) {
  const hex = crypto.createHash('sha256').update(bytes).digest('hex').slice(0, 32)
  return [...hex].map((c) => String.fromCharCode(97 + parseInt(c, 16))).join('')
}

function run(cmd, cmdArgs, opts) {
  const res = spawnSync(cmd, cmdArgs, { stdio: 'inherit', ...opts })
  if (res.status !== 0) process.exit(res.status ?? 1)
}

console.log(`▶ Building extension [${config.mode}] → API ${config.apiBase}`)

// 1. Clean output
fs.rmSync(DIST_DIR, { recursive: true, force: true })
fs.mkdirSync(DIST_DIR, { recursive: true })

// 2. Popup (Vite reads the same config via EXT_MODE, see popup-src/vite.config.js)
if (!fs.existsSync(path.join(POPUP_SRC, 'node_modules'))) {
  run('npm', ['install'], { cwd: POPUP_SRC })
}
run('npm', ['run', 'build'], { cwd: POPUP_SRC, env: { ...process.env, EXT_MODE: config.mode } })

// 3. Service worker + generated runtime config
fs.copyFileSync(path.join(EXTENSION_DIR, 'background.js'), path.join(DIST_DIR, 'background.js'))
fs.writeFileSync(
  path.join(DIST_DIR, 'config.js'),
  `// Generated by extension/build/build.mjs — do not edit.\n` +
    `export const API_BASE = ${JSON.stringify(config.apiBase)};\n`,
)

// 3.5 Offscreen Document
fs.copyFileSync(path.join(EXTENSION_DIR, 'offscreen.html'), path.join(DIST_DIR, 'offscreen.html'))
run('npx', [
  'esbuild', 'offscreen.js', 
  '--bundle', 
  '--outfile=dist/offscreen-bundle.js',
  '--external:jsdom',
  '--external:path',
  '--external:url',
  '--external:fs',
  '--external:vm',
  '--external:stream',
  '--external:crypto'
], { cwd: EXTENSION_DIR })

// 4. Manifest
const manifest = buildManifest(config)
fs.writeFileSync(path.join(DIST_DIR, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n')

// 5. Report the extension ID the web app must use (EXTENSION_ID in .env)
if (config.mode === 'development') {
  const id = config.extensionKey
    ? extensionIdFrom(Buffer.from(config.extensionKey, 'base64'))
    : extensionIdFrom(Buffer.from(fs.realpathSync(DIST_DIR), 'utf8')) // unpacked, macOS/Linux
  const source = config.extensionKey ? 'pinned by EXTENSION_KEY' : 'derived from the unpacked path'
  console.log(`\n✔ Load unpacked from: ${DIST_DIR}`)
  console.log(`  Extension ID (${source}): ${id}`)
  console.log(`  Put it into .env as EXTENSION_ID=${id} (verify on chrome://extensions)`)
}

// 6. Store package
if (shouldZip) {
  const zipName = `job-tracker-extension-${manifest.version}${config.mode === 'production' ? '' : `-${config.mode}`}.zip`
  const zipPath = path.join(EXTENSION_DIR, zipName)
  fs.rmSync(zipPath, { force: true })
  run('zip', ['-r', '-X', '-q', zipPath, '.'], { cwd: DIST_DIR })
  console.log(`\n✔ Store package: ${zipPath}`)
}
